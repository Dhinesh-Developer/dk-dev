"""Turn your LinkedIn data export into the post library shown on the LinkedIn page.

1. On LinkedIn: Settings > Data privacy > Get a copy of your data > choose "Posts" (or "Want something in particular?")
   and request the archive. Download it when LinkedIn emails you and unzip it.
2. Run (from the project folder):
       python tools/import_linkedin.py path/to/Shares.csv            # newest 50 posts
       python tools/import_linkedin.py path/to/Shares.csv --limit 30
   Or use your own CSV with the columns: title,url,date,tag,likes,comments
       python tools/import_linkedin.py my_posts.csv
3. It writes js/data-posts.js. Reload the site.

LinkedIn's export does not include reaction counts. To rank by reactions, add `likes` and `comments`
columns to the CSV yourself (copy the numbers from each post); the page then offers "Most reactions".
"""
import argparse, csv, json, os, re, sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "js", "data-posts.js")
TAGS = [("AI", r"\b(ai|llm|rag|agent|langchain|langgraph|genai|gemini|ollama|mcp)\b"), ("SDET", r"\b(selenium|playwright|testng|pytest|testing|automation|sdet|cucumber)\b"),
        ("DSA", r"\b(leetcode|dsa|algorithm|striver|takeuforward|tuf|problem solving)\b"), ("Java", r"\b(java|spring|hibernate|jpa|jwt)\b"),
        ("Design", r"\b(system design|hld|lld|design pattern)\b"), ("Event", r"\b(hackathon|workshop|certificate|internship|event|award|hall of fame)\b")]

def title_of(text: str) -> str:
    first = next((l.strip() for l in re.split(r"[\r\n]+", text) if l.strip()), "Post")
    first = re.sub(r"\s+", " ", first)
    return first if len(first) <= 95 else first[:92].rstrip() + "..."

def tag_of(text: str) -> str:
    low = text.lower()
    for name, pat in TAGS:
        if re.search(pat, low): return name
    return "Update"

def load(path: str):
    with open(path, newline="", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    posts = []
    for r in rows:
        if "ShareLink" in r:                      # LinkedIn export format
            text = r.get("ShareCommentary", "") or ""
            if not text.strip() or not r.get("ShareLink"): continue
            posts.append({"title": title_of(text), "url": r["ShareLink"].strip(), "date": (r.get("Date") or "")[:10], "tag": tag_of(text)})
        else:                                     # hand-made CSV
            if not r.get("url"): continue
            posts.append({"title": r.get("title", "Post"), "url": r["url"].strip(), "date": (r.get("date") or "")[:10], "tag": r.get("tag") or tag_of(r.get("title", "")),
                          "likes": int(r["likes"]) if (r.get("likes") or "").isdigit() else 0, "comments": int(r["comments"]) if (r.get("comments") or "").isdigit() else 0})
    return posts

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv"); ap.add_argument("--limit", type=int, default=50)
    a = ap.parse_args()
    posts = load(a.csv)
    posts.sort(key=lambda p: (p.get("likes", 0) + p.get("comments", 0), p["date"]), reverse=True) if any(p.get("likes") for p in posts) else posts.sort(key=lambda p: p["date"], reverse=True)
    posts = posts[: a.limit]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/import_linkedin.py */\nwindow.DATA = window.DATA || {};\nDATA.posts = " + json.dumps(posts, indent=1, ensure_ascii=False) + ";\n")
    print(f"Wrote {len(posts)} posts to js/data-posts.js")

if __name__ == "__main__":
    sys.exit(main())
